using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Npgsql;
using Qontract.Domain.Models;
using Qontract.Infrastructure.Data;

namespace Qontract.Tests;

/// <summary>
/// Runs only when QONTRACT_TEST_POSTGRES holds a connection string for a
/// PostgreSQL role that may create databases (CI provides a service
/// container). Each test works in its own throwaway database.
/// </summary>
public sealed class PostgresFactAttribute : FactAttribute
{
    public const string Variable = "QONTRACT_TEST_POSTGRES";

    public PostgresFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable(Variable)))
            Skip = $"Set {Variable} to a PostgreSQL connection string to run.";
    }
}

public class PostgreSqlSupportTests
{
    private static ApplicationDbContext Context(string provider, string connectionString)
    {
        var options = new DbContextOptionsBuilder<ApplicationDbContext>();
        options.Configure(provider, connectionString);
        return new ApplicationDbContext(options.Options);
    }

    [Theory]
    [InlineData(DatabaseProvider.Sqlite, "Data Source=unused.sqlite")]
    [InlineData(DatabaseProvider.PostgreSql, "Host=localhost;Database=unused")]
    public void Migration_chain_matches_the_model(string provider, string connectionString)
    {
        // A model change needs a migration in BOTH chains:
        //   dotnet ef migrations add <Name> --project Qontract.Infrastructure --startup-project Qontract.Infrastructure
        //   dotnet ef migrations add <Name> --project Qontract.Infrastructure.PostgreSql --startup-project Qontract.Infrastructure.PostgreSql
        using var db = Context(provider, connectionString);
        Assert.NotEmpty(db.Database.GetMigrations());
        Assert.False(db.Database.HasPendingModelChanges(), $"The {provider} migration chain is behind the model.");
    }

    [Fact]
    public void PostgreSql_chain_uses_native_column_types()
    {
        using var db = Context(DatabaseProvider.PostgreSql, "Host=localhost;Database=unused");
        var script = db.GetService<IMigrator>().GenerateScript();

        Assert.Contains("timestamp with time zone", script);
        Assert.Contains("uuid", script);
        Assert.Contains("boolean", script);
        Assert.DoesNotContain("GENERATED BY DEFAULT AS IDENTITY", script);
        Assert.DoesNotContain("LocalSourceLedger", script);
    }

    [Fact]
    public async Task Copy_round_trips_every_table_and_skips_unmapped_ones()
    {
        await using var sourceFile = await SeededSqliteAsync();
        using var targetFile = new TemporarySqliteFile();
        // Read-only, exactly like the migrate-sqlite-to-postgres command.
        await using var source = Context(DatabaseProvider.Sqlite, sourceFile.ConnectionString + ";Mode=ReadOnly");
        await using var target = Context(DatabaseProvider.Sqlite, targetFile.ConnectionString);

        var report = await DatabaseCopier.CopyAsync(source, target);

        Assert.Equal(target.Model.GetRelationalModel().Tables.Count(), report.Tables.Count);
        Assert.Equal(["LocalSourceLedger"], report.SkippedSourceTables);
        await AssertSeedCopiedAsync(target);
    }

    [Fact]
    public async Task Copy_refuses_a_target_that_already_has_data()
    {
        await using var sourceFile = await SeededSqliteAsync();
        using var targetFile = new TemporarySqliteFile();
        await using (var source = Context(DatabaseProvider.Sqlite, sourceFile.ConnectionString))
        await using (var target = Context(DatabaseProvider.Sqlite, targetFile.ConnectionString))
            await DatabaseCopier.CopyAsync(source, target);

        await using var again = Context(DatabaseProvider.Sqlite, sourceFile.ConnectionString);
        await using var occupied = Context(DatabaseProvider.Sqlite, targetFile.ConnectionString);
        var error = await Assert.ThrowsAsync<DatabaseCopyException>(() => DatabaseCopier.CopyAsync(again, occupied));
        Assert.Contains("already contains data", error.Message);
    }

    [Fact]
    public async Task Copy_refuses_a_source_that_is_not_fully_migrated()
    {
        using var sourceFile = new TemporarySqliteFile();
        using var targetFile = new TemporarySqliteFile();
        await using var source = Context(DatabaseProvider.Sqlite, sourceFile.ConnectionString);
        var migrations = source.Database.GetMigrations().ToList();
        await source.GetService<IMigrator>().MigrateAsync(migrations[^2]);
        await using var target = Context(DatabaseProvider.Sqlite, targetFile.ConnectionString);

        var error = await Assert.ThrowsAsync<DatabaseCopyException>(() => DatabaseCopier.CopyAsync(source, target));
        Assert.Contains("missing 1 migration", error.Message);
        Assert.False(File.Exists(targetFile.Path) && new FileInfo(targetFile.Path).Length > 0);
    }

    [Fact]
    public async Task Copy_lists_values_the_target_schema_would_reject_before_writing()
    {
        await using var sourceFile = await SeededSqliteAsync();
        await using (var raw = new SqliteConnection(sourceFile.ConnectionString))
        {
            await raw.OpenAsync();
            await using var command = raw.CreateCommand();
            command.CommandText = "UPDATE Contracts SET Title = $title WHERE Title = 'Strom'";
            command.Parameters.AddWithValue("$title", new string('x', 201));
            Assert.Equal(1, await command.ExecuteNonQueryAsync());
        }
        using var targetFile = new TemporarySqliteFile();
        await using var source = Context(DatabaseProvider.Sqlite, sourceFile.ConnectionString);
        await using var target = Context(DatabaseProvider.Sqlite, targetFile.ConnectionString);

        var error = await Assert.ThrowsAsync<DatabaseCopyException>(() => DatabaseCopier.CopyAsync(source, target));

        Assert.Contains("Contracts.Title", error.Message);
        Assert.Contains("201 characters, column allows 200", error.Message);
        Assert.Equal(0, await target.Contracts.IgnoreQueryFilters().CountAsync());
    }

    [PostgresFact]
    public async Task Migrations_apply_on_postgres_with_native_types()
    {
        await using var database = await TemporaryPostgresDatabase.CreateAsync();
        await using var db = Context(DatabaseProvider.PostgreSql, database.ConnectionString);

        await db.Database.MigrateAsync();

        Assert.Empty(await db.Database.GetPendingMigrationsAsync());
        var type = await db.Database.SqlQueryRaw<string>(
            "SELECT data_type AS \"Value\" FROM information_schema.columns WHERE table_name = 'Users' AND column_name = 'CreatedAt'").SingleAsync();
        Assert.Equal("timestamp with time zone", type);
    }

    [PostgresFact]
    public async Task Copy_into_postgres_round_trips_and_the_app_keeps_writing()
    {
        await using var sourceFile = await SeededSqliteAsync();
        await using var database = await TemporaryPostgresDatabase.CreateAsync();
        await using (var source = Context(DatabaseProvider.Sqlite, sourceFile.ConnectionString))
        await using (var target = Context(DatabaseProvider.PostgreSql, database.ConnectionString))
        {
            var report = await DatabaseCopier.CopyAsync(source, target);
            Assert.Contains("LocalSourceLedger", report.SkippedSourceTables);
        }

        await using var db = Context(DatabaseProvider.PostgreSql, database.ConnectionString);
        await AssertSeedCopiedAsync(db);
        var session = await db.AuthSessions.SingleAsync();
        Assert.Equal(DateTimeKind.Utc, session.CreatedAt.Kind);
        Assert.Equal(SessionCreatedAt.Ticks - SessionCreatedAt.Ticks % 10, session.CreatedAt.Ticks);

        // Client-side keys continue after the copied rows, Unspecified/Local
        // timestamps are accepted, and serializable transactions work.
        var maxId = await db.Contracts.MaxAsync(c => c.Id);
        var tenant = await db.Tenants.SingleAsync();
        await using (var transaction = await db.BeginSerializableTransactionAsync())
        {
            var contract = new Contract { Title = "Neu", TenantId = tenant.Id, DeletedAt = DateTime.Now, RetentionExpiresAt = new DateTime(2027, 1, 1) };
            db.Contracts.Add(contract);
            await db.SaveChangesAsync();
            await transaction.CommitAsync();
            Assert.Equal(maxId + 1, contract.Id);
        }
        var invitation = new TenantInvitation { TenantId = tenant.Id, CodeHash = new string('b', 64), ExpiresAt = DateTime.UtcNow.AddDays(1) };
        db.TenantInvitations.Add(invitation);
        await db.SaveChangesAsync();
        var user = await db.Users.FirstAsync();
        Assert.True(await db.TryRedeemInvitationAsync(invitation.Id, user.Id, DateTime.UtcNow));
        // A captured local time is sent as a UTC parameter. (DateTime.Now inside
        // the query would translate to PostgreSQL's zone-less local time.)
        var cutoff = DateTime.Now;
        Assert.Equal(2, await db.Contracts.IgnoreQueryFilters().CountAsync(c => c.DeletedAt < cutoff));
    }

    private static readonly DateTime SessionCreatedAt = new DateTime(2026, 3, 4, 5, 6, 7, DateTimeKind.Utc).AddTicks(1234567);

    private static async Task<TemporarySqliteFile> SeededSqliteAsync()
    {
        var file = new TemporarySqliteFile();
        await using var db = Context(DatabaseProvider.Sqlite, file.ConnectionString);
        await db.Database.MigrateAsync();

        var tenant = new Tenant { Name = "Familie Müller 🚀", Type = TenantType.Family, IsActive = true };
        db.Tenants.Add(tenant);
        await db.SaveChangesAsync();
        var admin = new User { Name = "Admin", Email = "admin@example.test", PasswordHash = "hash", Role = UserRole.TenantAdmin, IsActive = true, TenantId = tenant.Id };
        var member = new User { Name = "Member", Email = "member@example.test", PasswordHash = "hash", Role = UserRole.User, IsActive = true };
        db.Users.AddRange(admin, member);
        await db.SaveChangesAsync();

        var contractor = new Contractor { Name = "Stadtwerke", Type = ContractorType.Company, TenantId = tenant.Id, OwnerUserId = admin.Id, IsActive = true };
        db.Contractors.Add(contractor);
        await db.SaveChangesAsync();
        var power = new Contract { Title = "Strom", Status = ContractStatus.Active, Type = ContractType.Other, TenantId = tenant.Id, ContractorId = contractor.Id, ResponsibleUserId = admin.Id, IsActive = true };
        var trashed = new Contract { Title = "Alt", Status = ContractStatus.Terminated, TenantId = tenant.Id, DeletedAt = new DateTime(2026, 1, 1, 0, 0, 0, DateTimeKind.Utc), RetentionExpiresAt = new DateTime(2026, 4, 1, 0, 0, 0, DateTimeKind.Utc) };
        db.Contracts.AddRange(power, trashed);
        db.Addresses.AddRange(
            new Address { EntityType = EntityType.Contractor, ContractorId = contractor.Id, Street = "Hauptstraße", City = "Köln" },
            new Address { EntityType = EntityType.Person, UserId = member.Id, City = "Bonn" });
        await db.SaveChangesAsync();

        db.ContractPrices.AddRange(
            new ContractPrice { ContractId = power.Id, Value = "80.00", Currency = "EUR", BillingPeriod = BillingPeriod.Monthly, EffectiveFrom = "2025-01-01", EffectiveUntil = "2025-12-31" },
            new ContractPrice { ContractId = power.Id, Value = "92.50", Currency = "EUR", BillingPeriod = BillingPeriod.Monthly, EffectiveFrom = "2026-01-01" });
        var oldVersion = new Document { FileName = "v1.pdf", FileType = "application/pdf", FilePath = "a/v1.pdf", TenantId = tenant.Id, ContractId = power.Id, Title = "Vertrag", DocumentDate = new DateTime(2025, 5, 1) };
        var newVersion = new Document { FileName = "v2.pdf", FileType = "application/pdf", FilePath = "a/v2.pdf", TenantId = tenant.Id, ContractId = power.Id, Version = 2 };
        newVersion.Contracts.Add(trashed);
        db.Documents.AddRange(oldVersion, newVersion);
        await db.SaveChangesAsync();
        oldVersion.SupersededById = newVersion.Id;
        db.DocumentLinks.Add(new DocumentLink { DocumentId = newVersion.Id, ContractId = trashed.Id });
        db.Invoices.Add(new Invoice { TenantId = tenant.Id, ContractId = power.Id, DocumentId = newVersion.Id, InvoiceDate = new DateOnly(2026, 2, 1), DueDate = new DateOnly(2026, 2, 15), Amount = 12.50m, Currency = "EUR" });
        db.AuthSessions.Add(new AuthSession { UserId = admin.Id, CreatedAt = SessionCreatedAt, ExpiresAt = SessionCreatedAt.AddDays(30) });
        db.PasswordResets.Add(new PasswordReset { UserId = member.Id, TokenHash = new string('a', 64), NormalizedEmail = "MEMBER@EXAMPLE.TEST", CreatedAt = SessionCreatedAt, ExpiresAt = SessionCreatedAt.AddHours(1) });
        db.TenantInvitations.Add(new TenantInvitation { TenantId = tenant.Id, CodeHash = new string('c', 64), ExpiresAt = SessionCreatedAt.AddDays(7), RedeemedAt = SessionCreatedAt.AddDays(1), RedeemedByUserId = member.Id });
        db.TenantMemberships.Add(new TenantMembership { UserId = member.Id, TenantId = tenant.Id, Role = UserRole.User });
        await db.SaveChangesAsync();

        // Leftover from the FamilyPlanner import: not part of the model.
        await db.Database.ExecuteSqlRawAsync("CREATE TABLE IF NOT EXISTS LocalSourceLedger (Entity TEXT NOT NULL, SourceId TEXT NOT NULL, TargetReference TEXT, RawJson TEXT NOT NULL, PRIMARY KEY(Entity, SourceId))");
        await db.Database.ExecuteSqlRawAsync("INSERT INTO LocalSourceLedger VALUES ('Users', '1', '1', '{{}}')");
        return file;
    }

    private static async Task AssertSeedCopiedAsync(ApplicationDbContext db)
    {
        Assert.Equal("Familie Müller 🚀", (await db.Tenants.SingleAsync()).Name);
        Assert.Equal(2, await db.Users.CountAsync());
        Assert.Equal(2, await db.TenantMemberships.CountAsync());
        Assert.Equal(2, await db.Contracts.IgnoreQueryFilters().CountAsync());
        Assert.Equal(2, await db.ContractPrices.CountAsync());
        Assert.Equal(2, await db.Addresses.CountAsync());
        var documents = await db.Documents.IgnoreQueryFilters().Include(d => d.Contracts).OrderBy(d => d.Id).ToListAsync();
        Assert.Equal(documents[1].Id, documents[0].SupersededById);
        Assert.Single(documents[1].Contracts);
        Assert.Single(await db.DocumentLinks.ToListAsync());
        var invoice = await db.Invoices.SingleAsync();
        Assert.Equal(12.50m, invoice.Amount);
        Assert.Equal(new DateOnly(2026, 2, 15), invoice.DueDate);
        Assert.Single(await db.AuthSessions.ToListAsync());
        Assert.Single(await db.PasswordResets.ToListAsync());
        Assert.NotNull((await db.TenantInvitations.SingleAsync()).RedeemedByUserId);
        Assert.Equal("Köln", (await db.Addresses.SingleAsync(a => a.ContractorId != null)).City);
    }

    private sealed class TemporarySqliteFile : IDisposable, IAsyncDisposable
    {
        public string Path { get; } = System.IO.Path.Combine(System.IO.Path.GetTempPath(), $"qontract-copy-{Guid.NewGuid():N}.sqlite");
        public string ConnectionString => $"Data Source={Path};Pooling=False";

        public void Dispose()
        {
            SqliteConnection.ClearAllPools();
            if (File.Exists(Path)) File.Delete(Path);
        }

        public ValueTask DisposeAsync()
        {
            Dispose();
            return ValueTask.CompletedTask;
        }
    }

    private sealed class TemporaryPostgresDatabase : IAsyncDisposable
    {
        private readonly string _admin;
        private readonly string _name;

        private TemporaryPostgresDatabase(string admin, string name, string connectionString)
        {
            _admin = admin;
            _name = name;
            ConnectionString = connectionString;
        }

        public string ConnectionString { get; }

        public static async Task<TemporaryPostgresDatabase> CreateAsync()
        {
            var admin = Environment.GetEnvironmentVariable(PostgresFactAttribute.Variable)!;
            var name = $"qontract_test_{Guid.NewGuid():N}";
            await using (var connection = new NpgsqlConnection(admin))
            {
                await connection.OpenAsync();
                await using var command = new NpgsqlCommand($"CREATE DATABASE \"{name}\"", connection);
                await command.ExecuteNonQueryAsync();
            }
            var target = new NpgsqlConnectionStringBuilder(admin) { Database = name };
            return new TemporaryPostgresDatabase(admin, name, target.ToString());
        }

        public async ValueTask DisposeAsync()
        {
            NpgsqlConnection.ClearAllPools();
            await using var connection = new NpgsqlConnection(_admin);
            await connection.OpenAsync();
            await using var command = new NpgsqlCommand($"DROP DATABASE IF EXISTS \"{_name}\" WITH (FORCE)", connection);
            await command.ExecuteNonQueryAsync();
        }
    }
}
